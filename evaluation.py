# --- Core Evaluation Functions (from Notebook) ---

def eval_task(prompt, resume, job_desc, ai_response):
    """Evaluate the generated summary against the prompt used."""
    if not client:
        return "Evaluation Client not initialized.", None

    # Format the prompt for the evaluator LLM
    # The notebook passed a list [prompt, resume, job_desc] - adapt this if needed
    # Assuming the prompt template itself is complex, maybe just pass its description or key parts.
    # For simplicity here, pass the structured prompt object and the response.
    # If `prompt` is the ChatPromptTemplate object, we might need its string representation.
    # Let's assume `prompt` is a string representation or description for the eval prompt.
    eval_input_prompt = f"Original Task Prompt Context:\n{str(prompt)}\n\nResume Snippet:\n{resume[:300]}...\n\nJob Desc Snippet:\n{job_desc[:300]}..."

    try:
        # Use low temperature for evaluation
        chat = client.chats.create(model="gemini-2.5-pro-exp-03-25", # Use a new model, can change
                                  config=types.GenerateContentConfig(temperature=0.5))

        # Generate the full text evaluation
        response_eval = chat.send_message(
          message=SUMMARY_PROMPT.format(prompt=eval_input_prompt, response=ai_response)
        )
        verbose_eval = response_eval.text

        # Coerce into the desired structure
        structured_output_config = types.GenerateContentConfig(
          response_mime_type="text/x.enum",
          response_schema=SummaryRating,
        )
        response_struct = chat.send_message(
          message="Convert the final score.", # Ask the chat model to extract the score
          config=structured_output_config,
        )
        structured_eval = response_struct.parsed # `.parsed` is correct for client.chats

        return verbose_eval, structured_eval

    except Exception as e:
        print(f"Error during pointwise eval_task: {e}")
        return f"Error during evaluation: {e}", None


def eval_pairwise(prompt, resume, job_desc, response_a, response_b):
    """Determine the better of two answers to the same prompt."""
    if not client:
        return "Evaluation Client not initialized.", None

    # Similar prompt formatting as eval_task
    eval_input_prompt = f"Original Task Prompt Context:\n{str(prompt)}\n\nResume Snippet:\n{resume[:300]}...\n\nJob Desc Snippet:\n{job_desc[:300]}..."

    try:
        chat = client.chats.create(model="gemini-2.5-pro-exp-03-25", # Use a new model to try
                                  config=types.GenerateContentConfig(temperature=0.5))

        # Generate the full text comparison
        response_eval = chat.send_message(
          message=QA_PAIRWISE_PROMPT.format(
              prompt=eval_input_prompt,
              baseline_model_response=response_a,
              response=response_b)
        )
        verbose_eval = response_eval.text

        # Coerce into the desired structure
        structured_output_config = types.GenerateContentConfig(
          response_mime_type="text/x.enum",
          response_schema=AnswerComparison,
        )
        response_struct = chat.send_message(
          message="Convert the final preference (A, B, or SAME).", # Ask to extract preference
          config=structured_output_config,
        )
        structured_eval = response_struct.parsed # `.parsed` is correct

        return verbose_eval, structured_eval

    except Exception as e:
        print(f"Error during pairwise eval_pairwise: {e}")
        return f"Error during pairwise evaluation: {e}", None


# --- Evaluation Runner Functions ---

def mul_eval_task(llm, prompt, resume, job_desc, evac_func, NUM_ITERATIONS=1, filename="pointwise_comparison_result.txt"):
    """Runs multiple pointwise evaluations and saves results."""
    scores = collections.defaultdict(int)
    responses = collections.defaultdict(list)
    valid_evals = 0

    # Need the LLM object passed in to get model name, assuming it has .model attribute
    model_name = getattr(llm, 'model', 'unknown_model')
    print(f"\n--- Running {NUM_ITERATIONS} Pointwise Evals for Model: {model_name} ---")

    for n in range(NUM_ITERATIONS):
        print(f"\nIteration {n+1}/{NUM_ITERATIONS}")
        # Generate a response using the passed function
        # Ensure 'evac_func' matches the signature used in the notebook, e.g., generate_fit_score
        try:
            summary = evac_func(llm, prompt, resume, job_desc)
            print("  Generation successful.")
            if "Error generating" in summary: # Check for errors from generation func
                 raise ValueError("Generation function returned an error string.")
        except Exception as gen_e:
             print(f"  Error during generation step: {gen_e}")
             summary = f"Generation Error: {gen_e}"
             # Skip evaluation if generation failed
             responses[model_name].append((summary, "N/A - Generation Failed"))
             time.sleep(1)
             continue

        # Evaluate the response
        print("  Evaluating response...")
        # Pass the original prompt template/context used for generation
        written_eval, struct_eval = eval_task(prompt, resume, job_desc, summary)

        if struct_eval and isinstance(struct_eval, SummaryRating):
            print(f'  {model_name}: {struct_eval}')
            try:
                scores[model_name] += int(struct_eval.value)
                valid_evals += 1
            except (ValueError, TypeError):
                 print(f"  Warning: Could not convert score {struct_eval.value} to int.")
                 struct_eval = None # Mark as invalid for scoring
        else:
            print(f"  Evaluation failed or score not parsed: {struct_eval}")
            print(f"  Eval Text Snippet: {written_eval[:200]}...")
            struct_eval = None # Mark as invalid

        # Save the responses and evaluation text regardless of score parsing
        responses[model_name].append((summary, written_eval))

        time.sleep(5) # Avoid rate limits, for free version, still will hit rate limits

    avg_score = scores[model_name] / valid_evals if valid_evals > 0 else 0
    print(f"\n--- Pointwise Summary for {model_name} ---")
    print(f"Total Valid Evaluations: {valid_evals}/{NUM_ITERATIONS}")
    print(f"Average Score: {avg_score:.2f}")

    # Save results to file
    try:
        with open(filename, 'a', encoding='utf-8') as f:
            f.write(f"\n===== Pointwise Eval Run: {time.strftime('%Y-%m-%d %H:%M:%S')} =====\n")
            f.write(f"Model Evaluated: {model_name}\n")
            f.write(f"Number of Runs: {NUM_ITERATIONS}\n")
            f.write(f"Average Score: {avg_score:.2f} (based on {valid_evals} valid evals)\n")
            f.write(f"Prompt Context Used:\n{str(prompt)}\n")
            f.write("="*40 + "\n\n")
            run_num = 1
            for response_text, eval_text in responses[model_name]:
                f.write(f"--- Run: {run_num} ---\n")
                f.write("Generated Response:\n")
                f.write(f"{response_text}\n\n")
                f.write("Evaluation Details:\n")
                f.write(f"{eval_text}\n\n")
                run_num += 1
            print(f"Successfully appended results to '{filename}'.")
    except Exception as e:
        print(f"Error saving pointwise results to file '{filename}': {e}")

    return (model_name, avg_score)


class ModelComparisonRunner:
    """Runs N pairwise comparisons between two models for a given task."""

    # Ensure constructor matches the one in the notebook used for calling
    # The notebook used: prompt, llm_a, llm_b, resume, job_desc, eval_func, n_runs
    def __init__(self, prompt, llm_a, llm_b, resume, job_desc, eval_func, n_runs=2):
        self.prompt = prompt # The prompt template for the generation task
        self.llm_a = llm_a
        self.llm_b = llm_b
        self.resume = resume
        self.job_desc = job_desc
        self.generation_func = eval_func # The function to generate responses (e.g., generate_cover_letter)
        self.n = n_runs
        self.results = []

    def run_comparisons(self):
        """Generates responses and runs pairwise evaluation N times."""
        model_a_name = getattr(self.llm_a, 'model', 'Model_A')
        model_b_name = getattr(self.llm_b, 'model', 'Model_B')
        print(f"\n--- Running {self.n} Pairwise Comparisons ---")
        print(f"Model A: {model_a_name}")
        print(f"Model B: {model_b_name}")

        self.results = []
        for i in range(self.n):
            print(f"\n--- Comparison Run {i+1}/{self.n} ---")
            response_a, response_b = "Error", "Error" # Initialize
            # Step 1: Generate Response A
            try:
                 print("  Generating response A...")
                 # Call the generation function passed during init (e.g., generate_cover_letter)
                 # Adapt arguments if the generation function needs more/less context
                 response_a = self.generation_func(self.llm_a, self.prompt, self.resume, self.job_desc)
                 if "Error generating" in response_a: raise ValueError("Gen func A error")
                 print("    Generation A successful.")
            except Exception as e:
                 print(f"    Error generating response A: {e}")
                 response_a = f"Error generating response A: {e}"
            time.sleep(5)

            # Step 2: Generate Response B
            try:
                 print("  Generating response B...")
                 response_b = self.generation_func(self.llm_b, self.prompt, self.resume, self.job_desc)
                 if "Error generating" in response_b: raise ValueError("Gen func B error")
                 print("    Generation B successful.")
            except Exception as e:
                 print(f"    Error generating response B: {e}")
                 response_b = f"Error generating response B: {e}"
            time.sleep(5)

            # Step 3: Evaluate
            text_eval, struct_eval = "N/A", None
            if "Error generating" in response_a or "Error generating" in response_b:
                print("  Skipping evaluation due to generation error.")
                text_eval = "N/A (Generation Error)"
            else:
                print("  Evaluating Response A vs Response B...")
                try:
                    text_eval, struct_eval = eval_pairwise(
                        self.prompt, self.resume, self.job_desc, response_a, response_b
                    )
                    print(f"  Evaluation Result: {struct_eval}")
                except Exception as e:
                     print(f"  Error during pairwise evaluation call: {e}")
                     text_eval = f"Error during pairwise evaluation call: {e}"
                     struct_eval = None

            self.results.append({
                'run': i+1,
                'response_a': response_a,
                'response_b': response_b,
                'text_eval': text_eval,
                'structured_eval': struct_eval
            })
            time.sleep(5) # Delay between full comparison runs

        print("\n--- All Pairwise Comparison Runs Complete ---")
        return self.results

    def get_summary(self):
        """Summarize the results of the comparisons."""
        if not self.results:
            print("No comparison results available.")
            return None

        model_a_name = getattr(self.llm_a, 'model', 'Model_A')
        model_b_name = getattr(self.llm_b, 'model', 'Model_B')

        print("\n--- Pairwise Comparison Summary ---")
        choices = [run['structured_eval'] for run in self.results if isinstance(run.get('structured_eval'), AnswerComparison)]

        if not choices:
            print("No successful structured evaluations recorded.")
            return {"counts": Counter(), "preference": "Inconclusive (No valid evals)"}

        print(f"Structured choices across {len(choices)} successful evaluations: {choices}")
        counts = Counter(choices)
        a_wins = counts.get(AnswerComparison.A, 0)
        b_wins = counts.get(AnswerComparison.B, 0)
        same_count = counts.get(AnswerComparison.SAME, 0)

        print(f"Preference Counts: Model A ({model_a_name}) Wins={a_wins}, Model B ({model_b_name}) Wins={b_wins}, Same={same_count}")

        overall_preference = "Inconclusive"
        if a_wins > b_wins: overall_preference = f"Model A ({model_a_name}) preferred"
        elif b_wins > a_wins: overall_preference = f"Model B ({model_b_name}) preferred"
        elif a_wins == b_wins and a_wins > 0: overall_preference = "Models performed equally well"
        elif same_count > 0 and a_wins == 0 and b_wins == 0: overall_preference = "Models consistently rated as SAME"
        elif a_wins == 0 and b_wins == 0 and same_count == 0: overall_preference = "Inconclusive (No preference votes)"

        print(f"Overall Result: {overall_preference}")
        summary_data = {
            "counts": counts,
            "preference": overall_preference,
            "wins_a": a_wins,
            "wins_b": b_wins,
            "same": same_count
        }
        return summary_data

    def save_results_to_file(self, filename="comparison_results.txt"):
        """Saves the detailed results of all runs to a text file."""
        if not self.results:
            print("No results to save. Run run_comparisons() first.")
            return

        model_a_name = getattr(self.llm_a, 'model', 'Unknown Model A')
        model_b_name = getattr(self.llm_b, 'model', 'Unknown Model B')

        print(f"\nAppending detailed pairwise results to '{filename}'...")
        try:
            # Use append mode 'a'
            with open(filename, 'a', encoding='utf-8') as f:
                f.write(f"\n===== Pairwise Comparison Run Set: {time.strftime('%Y-%m-%d %H:%M:%S')} =====\n")
                f.write(f"Model A: {model_a_name}\n")
                f.write(f"Model B: {model_b_name}\n")
                # Include Job Description Context used for this run set
                # Truncate job_desc if it's very long
                jd_snippet = self.job_desc[:1000] + "..." if len(self.job_desc) > 1000 else self.job_desc
                f.write(f"Job Description Context (Snippet):\n{jd_snippet}\n")
                f.write(f"Number of Runs: {self.n}\n")
                f.write(f"Prompt Context Used:\n{str(self.prompt)}\n") # Save prompt used
                f.write("="*40 + "\n\n")

                for result in self.results:
                    f.write(f"--- Run {result['run']}/{self.n} ---\n\n")
                    f.write(f"Response A ({model_a_name}):\n")
                    f.write(f"{result.get('response_a', 'N/A')}\n\n")
                    f.write(f"Response B ({model_b_name}):\n")
                    f.write(f"{result.get('response_b', 'N/A')}\n\n")
                    f.write("Pairwise Evaluation:\n")
                    struct_choice = result.get('structured_eval')
                    # Use .name for enum, handle None case
                    choice_str = struct_choice.name if isinstance(struct_choice, AnswerComparison) else 'N/A'
                    f.write(f"  Structured Choice: {choice_str}\n")
                    f.write(f"  Verbose Reasoning:\n{result.get('text_eval', 'N/A')}\n")
                    f.write("\n" + "="*40 + "\n\n")

            # Also append the summary
            summary = self.get_summary() # Recalculate or retrieve stored summary
            if summary:
                 with open(filename, 'a', encoding='utf-8') as f:
                    f.write("\n--- Summary of this Run Set ---\n")
                    f.write(f"Preference: {summary['preference']}\n")
                    f.write(f"Counts: A={summary['wins_a']}, B={summary['wins_b']}, SAME={summary['same']}\n")
                    f.write("="*40 + "\n\n")

            print(f"Successfully appended results to '{filename}'.")
        except Exception as e:
            print(f"Error saving pairwise results to file '{filename}': {e}")


